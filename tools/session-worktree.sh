#!/bin/sh
# ═══════════════════════════════════════════════════════════════════════
#  worktreeِ اختصاصیِ یک نشست — با node_modulesِ به‌اشتراک‌گذاشته‌شده
#
#  چرا این وجود دارد (۲۰۲۶-۰۹-۱۰، تصمیمِ CEO پس از دو تصادمِ واقعی):
#  هفت نشست روی یک درختِ کاری می‌نوشتند. دو بار در یک روز، کامیتِ یک نشست
#  کارِ commitنشده‌ی نشستِ دیگر را با خود برد:
#
#      859c115  پیام: «ردیفِ Designer»   →  سه ردیف از سه نشست
#      939bca1  پیام: «گاردِ فونت»        →  به‌اضافه‌ی کلِ FG-12ِ رد تیم
#
#  چیزی گم نشد، ولی رکورد خراب شد: جست‌وجوی FG-12 در تاریخچه، کامیتی
#  درباره‌ی فونت می‌دهد.
#
#  ⚠️ و چرا انضباط کافی نبود — این نکته‌ی اصلی است:
#  در همان روز **دو نشست عمداً از commit خودداری کردند** تا کارِ هم را
#  نبرند، و نشستِ سومی که این احتیاط را نداشت فایل را commit کرد و هر دو را
#  برد. رد تیم صورت‌بندی‌اش کرد: «دو نفر که مراقب باشند درختِ مشترک را امن
#  نمی‌کند — فقط آن‌ها را کندتر می‌کند از کسی که مراقب نیست.»
#
#  ⚠️ مانعِ قبلیِ worktree هزینه بود و **اندازه‌گیری شد، نه فرض**:
#      api/node_modules ۵۸۹M · landing ۴۴۸M · seo ۴۴۷M  ≈ ۱.۵G هر worktree
#  با junctionِ ویندوز آن هزینه صفر می‌شود. اثباتِ اجراشده در worktreeِ
#  آزمایشی: `npx tsc --noEmit` → exit 0، و یک تستِ واقعیِ دیتابیس ۴/۴ سبز.
#  یعنی worktree فقط برای سند نیست؛ کارِ کدمحور هم کامل در آن اجرا می‌شود.
# ═══════════════════════════════════════════════════════════════════════
set -e
NAME="${1:?استفاده: sh tools/session-worktree.sh <نامِ-نشست>   (مثلاً rezv-d6)}"
ROOT="$(git rev-parse --show-toplevel)"
DEST="$(dirname "$ROOT")/wt-$NAME"

if [ -d "$DEST" ]; then
  echo "worktree از قبل هست: $DEST"
else
  git -C "$ROOT" worktree add "$DEST" -b "session/$NAME"
fi

# node_modules از درختِ اصلی به اشتراک گذاشته می‌شود — کپی نمی‌شود.
# ⚠️ فقط جایی که در درختِ اصلی واقعاً نصب است؛ نبودش خطا نیست، چون هر
# نشستی به هر سه اپ کار ندارد.
for sub in api apps/landing apps/seo; do
  SRC="$ROOT/$sub/node_modules"
  DST="$DEST/$sub/node_modules"
  [ -d "$SRC" ] || continue
  [ -e "$DST" ] && continue
  mkdir -p "$(dirname "$DST")"
  cmd //c mklink //J "$(cygpath -w "$DST")" "$(cygpath -w "$SRC")" >/dev/null 2>&1 \
    && echo "  اشتراک: $sub/node_modules" \
    || echo "  ⚠️ junction برای $sub ساخته نشد — اگر تست لازم داری، آنجا npm ci بزن"
done

echo ""
echo "آماده:  $DEST"
echo "شاخه:   session/$NAME"
echo ""
echo "از این به بعد همه‌ی کارت را آنجا انجام بده. وقتی چیزی آماده‌ی اشتراک شد:"
echo "  git -C \"$DEST\" push -u origin session/$NAME"
echo "و به CEO بگو تا در main ادغامش کند — یا اگر مسیرت با کسی تداخل ندارد،"
echo "خودت rebase و push کن. ⚠️ هرگز از worktree روی درختِ اصلی commit نکن."
