/* ═══════════════════════════════════════════════════════════
   رزرونو — helperهای خالصِ نمایش/امنیت (منبعِ واحد؛ فقط پنل‌ها)
   این فایل منبعِ حقیقت است؛ tools/sync-design-system.sh نسخه‌ی global آن را
   به پنل‌های business/company می‌سازد (export حذف می‌شود؛ برای <script> کلاسیک).

   نکته: اپ customer عمداً اینجا نیست — `fa` در customer معنایِ متفاوتی دارد
   (تبدیلِ رقمِ ASCII به فارسی، نه فرمتِ عددِ fa-IR)، پس نباید یکی شود.

   fa  : فرمتِ عدد با جداکننده‌ی فارسی (۱۲٬۳۴۵).
   esc : escape کردنِ ورودی قبل از تزریق به HTML (ضدِّ XSS) — تنها پیاده‌سازیِ
         کانونیِ پنل‌ها؛ رفعِ باگِ escape یک‌جا برای هر دو پنل اعمال می‌شود.
   ═══════════════════════════════════════════════════════════ */
function fa(n){return (n==null||Number.isNaN(n))?'۰':n.toLocaleString('fa-IR')}
function esc(s){return String(s==null?'':s).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]))}
