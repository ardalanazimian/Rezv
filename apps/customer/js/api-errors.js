//  اندازه‌گیری‌شده:
//      grep -rnE "CONCURRENCY_RETRY|SLOT_LOCK_TIMEOUT|TABLE_CONFLICT" apps/  →  ۰
//  و تنها جایی که روی کد **شاخه** می‌زد، `booking.js` بود که در همان شرط یک
//  `/پر|ظرفیت/.test(error.message)` هم داشت.
//
//  چرا regex روی متنِ فارسی یک نقص است و نه یک سلیقه: پیامِ خطا **متنِ
//  کاربر** است، نه قرارداد. عوض‌کردنِ یک کلمه در `errors.ts` — یا حتی
//  اصلاحِ یک نیم‌فاصله — بی‌صدا منطقِ UI را می‌شکند، بدونِ آنکه هیچ تستی
//  قرمز شود. کد قرارداد است؛ پیام نیست.
//
//  ⚠️ تفکیکی که باید نوشته شود: **نمایشِ** `error.message` کاملاً درست است
//  و در کلِ اپ همین‌طور می‌ماند — سرور بهترین متن را می‌داند. چیزی که غلط
//  است **شاخه‌زدن** روی آن متن. فقط یک نقطه در کلِ اپِ کاستومر این کار را
//  می‌کرد و همان‌جا رفع شد.
//
//  منبعِ کدها: `api/src/lib/errors.ts` (سازنده‌های `Err.*`).
// ═══════════════════════════════════════════════════════════

/**
 * ظرفیت واقعاً تمام است — تلاشِ دوباره همین الان بی‌فایده است، ولی
 * لیستِ انتظار معنی دارد.
 */
export const CAPACITY_CODES = Object.freeze([
  'SLOT_FULL',          // errors.ts:35 — ساعت پر است
  'NO_TABLE_FOR_PARTY', // errors.ts:34 — میزی با این ظرفیت وجود ندارد
  // ⚠️ `MERGE_UNAVAILABLE` امروز **هرگز پرتاب نمی‌شود** — اندازه‌گیری‌شده:
  // در کلِ `api/src` فقط تعریفش در `errors.ts:43` هست و صفر جای پرتاب.
  // پس حضورش اینجا را کسی به‌عنوانِ «سرور این را برمی‌گرداند» نخواند؛
  // پیش‌دستی است برای وقتی که مسیرِ ترکیبِ میز واقعاً پیاده شود.
  // نگه داشته شد و حذف نشد چون اگر آن روز برسد، نبودنش یعنی کاربر به‌جای
  // پیشنهادِ صف یک توستِ عمومی می‌بیند — و پیامش نه «پر» دارد نه «ظرفیت»،
  // پس regexِ قبلی هم نمی‌گرفتش.
  'MERGE_UNAVAILABLE',  // errors.ts:43 — اعلام‌شده، پرتاب‌نشده
]);

/**
 * رقابتِ همزمان یا قفل — ظرفیت لزوماً تمام نیست؛ همین حالا دوباره تلاش‌کردن
 * منطقی است و اغلب جواب می‌دهد.
 *
 * ⚠️ `TABLE_CONFLICT` در مسیرِ کاستومر یعنی میزی که سرور **خودش** انتخاب
 * کرده بین انتخاب و درج گرفته شده — کاربر میز انتخاب نمی‌کند (انتخابِ دستیِ
 * میز مالِ پنلِ رستوران است). پس برای کاستومر یک رقابت است، نه یک خطای ورودی.
 */
export const RETRYABLE_CONFLICT_CODES = Object.freeze([
  'CONCURRENCY_RETRY',  // errors.ts:46 — از کامیتِ 38a9570 به بعد واقعاً برمی‌گردد
  'SLOT_LOCK_TIMEOUT',  // errors.ts:22 — بازه در حالِ رزرو توسطِ کاربرِ دیگر
  'TABLE_CONFLICT',     // errors.ts:21
]);

/**
 * دسته‌ی خطای مسیرِ رزرو: `'capacity' | 'retry' | 'other'`.
 * فقط روی **کد** تصمیم می‌گیرد؛ هرگز روی متنِ پیام.
 */
export function bookingErrorKind(error) {
  const code = error?.code;
  if (!code) return 'other';
  if (CAPACITY_CODES.includes(code)) return 'capacity';
  if (RETRYABLE_CONFLICT_CODES.includes(code)) return 'retry';
  return 'other';
}
