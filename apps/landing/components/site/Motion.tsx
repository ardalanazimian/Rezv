//
//  `Reveal` به‌عنوانِ یک پوسته‌ی ساده می‌ماند چون ده‌ها بلوکِ CMS و صفحه آن را
//  برای چیدمان (className) به کار می‌برند؛ حذفش فقط churn بود بی‌هیچ تغییرِ
//  رفتاری. دیگر جاوااسکریپتِ کلاینت ندارد.
