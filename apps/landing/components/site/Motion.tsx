//  می‌شد: آشکارسازیِ «محو و ۱۸px بالا» با IntersectionObserver، شمارنده‌ی
//  ۰→N برای عددها، و نوارِ پیشرفتِ اسکرول که --vel (کِشش با سرعتِ اسکرول)
