import type { ReactNode } from 'react';

export function Reveal({
  children,
  as: Tag = 'div',
  className,
}: {
  children: ReactNode;
  /** پذیرفته و نادیده گرفته می‌شود — امضای قبلی، تا فراخوان‌ها دست نخورند. */
  delay?: number;
  as?: 'div' | 'section' | 'li' | 'article' | 'header';
  className?: string;
}) {
  return <Tag className={className}>{children}</Tag>;
}
