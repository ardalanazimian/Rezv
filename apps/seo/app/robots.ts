import type { MetadataRoute } from 'next';

// ═══════════════════════════════════════════════════════════════════════
//  robots.txt این اپ فقط روی **مبدأِ مستقیمِ خودش** دیده می‌شود، نه روی apex.
//
//  چرا: `apps/landing/next.config.js` تنها `/r/*`، `/city/*`، `/cuisine/*` و
//  `/sitemap-restaurants.xml` را به اینجا rewrite می‌کند. `/robots.txt` جزوِ
//  آن‌ها نیست، پس `rezervno.ir/robots.txt` را همان لندینگ سرو می‌کند و این
//  فایل فقط از آدرسِ deploymentِ خودِ این اپ خوانده می‌شود.
//
//  نتیجه‌ی مهم: disallow کردن اینجا **هیچ اثری روی خزیدنِ صفحاتِ رستوران
//  از روی apex ندارد** — خزنده هنگام خزیدنِ `rezervno.ir/r/<slug>` قواعدِ
//  `rezervno.ir/robots.txt` را می‌خواند، که مالِ لندینگ است و اجازه می‌دهد.
//
//  ⚠️ پیش از ۲۰۲۶-۰۹-۰۸ این فایل `allow: '/'` می‌داد و `host: SITE` را ادعا
//  می‌کرد. یعنی هر جا این اپ مستقر می‌شد — از جمله هر preview — خودش را apex
//  اعلام می‌کرد و همان محتوا روی دو میزبان ایندکس‌پذیر می‌شد. محتوای تکراری،
//  و ممکن بود میزبانِ اشتباه برنده شود.
//
//  `host` هم برداشته شد: زیرِ rewrite، اعلامِ میزبانِ apex کارِ لندینگ است.
//  دو اپ که برای یک دامنه `host` اعلام کنند، دقیقاً همان نقصی است که تصمیمِ
//  D-004 برای بستنش گرفته شد.
// ═══════════════════════════════════════════════════════════════════════
export default function robots(): MetadataRoute.Robots {
  return {
    rules: { userAgent: '*', disallow: '/' },
  };
}
