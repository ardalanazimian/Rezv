//  نمی‌فرستد: رد شدن پس از **۳۰۳٬۶۵۷ میلی‌ثانیه** با
//  `UND_ERR_HEADERS_TIMEOUT` — یعنی ~۳۰۰ ثانیه فقط برای هدر، و `bodyTimeout`
//  جداگانه بعد از آن برای خواندنِ بدنه.
//
//  دو پیامد داشت، و هر دو واقعی‌اند:
//   ۱) یک ارائه‌دهنده‌ی کندِ پیامک می‌توانست ۵ دقیقه workerِ صف را ببندد و
//      چون batch **سریالی** پردازش می‌شود (`lib/worker.ts`)، ۴۹ کارِ دیگرِ
//      همان batch پشتِ آن می‌ماندند.
//   ۲) «اجاره»ی صف باید از یک سقفِ **واقعی** مشتق شود؛ با سقفِ ۳۰۰ ثانیه‌ای
//      undici اجاره‌ی امن به ساعت می‌رسید و عملاً بی‌مصرف می‌شد.
//
//  مقدار **اختراع نشده**: همان سقفی است که `deliverWebhook` از قبل داشت
//  (`lib/events.ts`، `AbortSignal.timeout(10_000)`). این فایل آن عدد را از
//  دلِ یک تابع بیرون کشید تا هر سه مسیرِ خروجی یک مرجع داشته باشند و
//  «اجاره» بتواند به همان نماد گره بخورد، نه به یک کپیِ عددی.
