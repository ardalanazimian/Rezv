/**
 * سقفِ هر فراخوانیِ HTTPِ خروجی (میلی‌ثانیه).
 *
 * ⚠️ اگر این عدد را بزرگ‌تر کردی، `JOB_LEASE_MS` در `lib/queue.ts` خودکار با
 * آن بزرگ می‌شود (از همین نماد مشتق شده است). این عمدی است: اجاره‌ای که از
 * طولانی‌ترین handler کوتاه‌تر باشد، کارِ **در حالِ اجرا** را بازپس می‌گیرد و
 * پیامک را دوبار می‌فرستد — بدتر از نقصی که قرار بود رفع کند.
 */
export const OUTBOUND_HTTP_TIMEOUT_MS = 10_000;

/**
 * `AbortSignal` استانداردِ همه‌ی fetchهای خروجی.
 *
 * تابع است نه ثابت: هر `AbortSignal.timeout` از لحظه‌ی **ساخته‌شدنش** شمارش
 * می‌کند، پس یک نمونه‌ی ماژول‌سطح بعد از ۱۰ ثانیه از بالا آمدنِ پروسه برای
 * همیشه abort شده می‌بود و هر فراخوانی را بی‌درنگ می‌شکست.
 */
export function outboundHttpSignal(): AbortSignal {
  return AbortSignal.timeout(OUTBOUND_HTTP_TIMEOUT_MS);
}
