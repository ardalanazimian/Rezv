import { Err } from './errors';

// ═══════════════════════════════════════════════════════════════════════
//  حصارِ ورودِ کارمند با پیامک — M-01 (حکمِ مالک، ۲۰۲۶-۰۹-۱۸)
//
//  حکم: «OTP رو فعلا دست نگه دار، برای پنل بیزنس شرکت از طریق پنل کمپانی
//  یوزر و پسورد تعریف میکنه، تو پنل بیزنس هم مدیر برای پرسنل باید بتونه
//  یوزر و پسورد جدا با دسترسی های مختلف تعریف کنه.»
//  یعنی احرازِ هویتِ پنلِ بیزنس/کمپانی = نام‌کاربری و رمز. پیامک «فعلاً» نه.
//
//  ── چرا این حصار امنیتی هم هست، نه فقط محصولی ──
//  M-01: `POST /v1/restaurant/staff` هر شماره‌ای را بدونِ هیچ اثباتِ مالکیت
//  به‌عنوانِ کارمند ثبت می‌کند، و `findStaffForLogin` (staff-helpers.ts:192)
//  کلِ پلتفرم را می‌گردد — اول ردیفِ owner، بعد قدیمی‌ترین. پس تنانتی که
//  شماره‌ی کارمندِ رستورانِ دیگری را زودتر ثبت کند، ورودِ آن شخص را می‌رباید.
//  رِدتیم (rezv-18) این را روی ba87829 زنده بازتولید کرد: با نبودِ ردیفِ
//  owner برای آن شماره، برنده‌ی جست‌وجو تنانتِ **مهاجم** است.
//  این یک مسابقه‌ی زمانی نیست؛ شرطش «زودتر ثبت‌کردن» است، پس در عمل همیشه
//  در دسترسِ مهاجم است.
//
//  ── چرا حصار و نه حذف ──
//  «فعلاً» زبانِ برگشت‌پذیر است، پس تغییر هم باید برگشت‌پذیر باشد. هیچ روتی
//  حذف نشده و `findStaffForLogin` سرِ جایش است؛ فقط **یک** سوییچ پایین.
//  برگرداندنش یک خط است. کدِ مرده‌ی حاضر با حصار صادقانه است؛ حذفش revert را
//  به بازنویسی تبدیل می‌کند.
//
//  ⚠️ این حصار نقصِ M-01 را **رفع نمی‌کند** — فقط تنها دو ورودی‌اش را می‌بندد.
//  `findStaffForLogin` هنوز همان جست‌وجوی پلتفرم‌گستر است. اگر روزی این سوییچ
//  روشن شود، نقص هم دقیقاً با همان شکل برمی‌گردد. رفعِ واقعی یعنی آن جست‌وجو
//  را تنانت‌محدود کردن یا ثبتِ کارمند را به اثباتِ مالکیتِ شماره گره زدن.
// ═══════════════════════════════════════════════════════════════════════

/**
 * تنها سوییچ. `false` = بسته (حالتِ امروز، طبقِ حکمِ مالک).
 *
 * عمداً ثابتِ کد است، نه env و نه فلگِ DB: هر دوی آن‌ها می‌توانند در یک محیط
 * اشتباه «روشن» تنظیم شوند و حصار بی‌صدا باز شود. ثابت یعنی حالتِ بسته
 * ساختاری است و برای بازکردنش باید کد عوض و بازبینی شود.
 */
export const STAFF_OTP_LOGIN_ENABLED = false;

/**
 * اگر حصار بسته است، خطای روشن پرتاب می‌کند — نه ۴۰۴ِ خاموش، نه ریدایرکت.
 * کدِ `FEATURE_DISABLED` از قبل برای همین معنی وجود دارد (kill-switchِ سطحِ
 * پلتفرم) و کلاینت می‌تواند ماشین‌خوان تشخیصش بدهد.
 */
export function assertStaffOtpLoginEnabled(): void {
  if (STAFF_OTP_LOGIN_ENABLED) return;
  throw Err.featureDisabled('ورودِ کارمند با پیامک');
}
