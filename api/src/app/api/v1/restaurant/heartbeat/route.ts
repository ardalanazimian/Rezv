import { NextResponse } from 'next/server';
import { db } from '@/lib/db';
import { withRestaurantAuth } from '@/lib/with-restaurant-auth';

/**
 * POST /api/v1/restaurant/heartbeat — پنل بیزنس هر ~۳۰ ثانیه این را صدا می‌زند
 * تا به سرور بگوید «اینترنتم وصل است». سرور last_seen_at را به‌روز می‌کند.
 *
 * چرا لازم است: وقتی اینترنت یک رستوران قطع می‌شود، پنل بیزنسش به سرور وصل نیست،
 * ولی سرور (که اپ مشتری از آن داده می‌گیرد) روی دیتاسنتری دیگر است و آنلاین است.
 * پس سرور از heartbeat می‌فهمد کدام رستوران زنده است. اگر مدتی heartbeat نیاید،
 * رستوران از اپ مشتری پنهان می‌شود تا رزرو آنلاینی ثبت نشود که با ثبت حضوریِ
 * آفلاینِ پرسنل تضاد پیدا کند (حذف کامل سناریوی رزرو دوبل).
 *
 * rateLimit سبک ('search') کافی است چون فراوان صدا زده می‌شود.
 *
 * ═══ چرا این route عمداً `permission:` ندارد (تصمیمِ ثبت‌شده، نه فراموشی) ═══
 *
 * در ممیزیِ RBAC این فایل به‌عنوانِ «routeِ بدونِ مجوز» علامت خورد. بررسی شد و
 * تصمیم این است که **همین‌طور بماند**، به سه دلیلِ قابلِ‌تأیید:
 *
 *  ۱) هیچ داده‌ای برنمی‌گرداند. کلِ پاسخ `{ ok: true, interval: 30 }` است —
 *     نه نامِ مهمان، نه شماره، نه رزرو. تنها اثرش نوشتنِ `lastSeenAt` رویِ
 *     رستورانِ **خودِ همان کارمند** است (`ctx.restaurant.id` که خودِ
 *     `resolveStaffRestaurant` با چکِ تنانت/شعبه ساخته). یعنی سطحِ حمله‌اش
 *     «اعلامِ آنلاین‌بودنِ رستورانِ خودت» است و بس.
 *
 *  ۲) گذاشتنِ مجوز رویش یک باگِ P1ِ تازه می‌سازد، نه رفعِ باگ. مصرف‌کننده‌اش
 *     `Heartbeat.start()` در `apps/business/js/staff-system.js` (خطوطِ ۵۴۸ و
 *     ۵۵۹) است که برایِ **هر** کاربرِ لاگین‌کرده اجرا می‌شود، بدونِ هیچ چکِ
 *     مجوزی، و `apps/business/js/data.js:580` هر ۳۰ ثانیه POST می‌زند. اگر
 *     مجوز بگذاریم، شیفتی که فقط یک کارمندِ محدود (مثلاً هاستِ فقط-لیستِ‌انتظار)
 *     پشتِ پنل دارد، هر heartbeat ۴۰۳ می‌گیرد → بعد از ۹۰ ثانیه شرطِ
 *     `lastSeenAt >= now-90s` در `restaurants/route.ts` رد می‌شود → رستوران از
 *     کاتالوگِ اپِ مشتری **ناپدید** می‌شود و رزروِ آنلاین قطع می‌شود. یعنی یک
 *     اختلالِ درآمدیِ خاموش، برایِ بستنِ دری که پشتش چیزی نیست.
 *
 *  ۳) خودِ liveness یک سیگنالِ زیرساختی است، نه یک قابلیتِ کسب‌وکار؛ هیچ‌کدام
 *     از ۹ کلیدِ `PermissionKey` معنایِ «حق دارد بگوید اینترنتم وصل است» را
 *     ندارند. ساختنِ کلیدِ تازه هم برایِ این، اختراعِ بی‌دلیل است (§۲۲).
 *
 * ⚠️ اگر روزی این endpoint چیزی بیش از `lastSeenAt` بنویسد یا داده‌ای برگرداند،
 *    این استدلال باطل است و باید دوباره تصمیم گرفته شود.
 *    گاردِ خودکار: `tests/rbac-permission-coverage.test.mts` این فایل را در
 *    فهرستِ صریحِ استثناها دارد؛ استثنایِ تازه باید عمدی و مستند باشد.
 */
export const POST = withRestaurantAuth(
  // بدونِ `permission:` — عمدی. دلیلِ کامل در بلوکِ بالا.
  { rateLimit: 'search' },
  async (_req, ctx) => {
    await db.restaurant.update({
      where: { id: ctx.restaurant.id },
      data: { lastSeenAt: new Date() },
    });
    // فاصله‌ی heartbeat پیشنهادی به کلاینت (ثانیه) — تا اگر خواستیم مرکزی تنظیمش کنیم
    return NextResponse.json({ ok: true, interval: 30 });
  },
);
