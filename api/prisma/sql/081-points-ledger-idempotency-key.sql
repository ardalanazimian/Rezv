-- ۰۸۱ — کلیدِ صریحِ idempotency روی دفترِ امتیاز (points_ledger)
--
-- زمینه: فازِ ۱ (پروتکل §۱۳) — «PHASE1-LEDGER-EVIDENCE» — نشان داد ledger
-- هیچ‌وقت `@@unique` نداشته و idempotencyِ اعطای امتیاز فقط از یک
-- compare-and-setِ اپلیکیشنی در lifecycle.ts می‌آید (تنها نویسنده‌ی مسیرِ
-- چک‌این). آن CAS با تستِ واقعی اثبات شد که درست کار می‌کند — این migration
-- ضامنِ ساختاری/دومِ سطحِ DB را اضافه می‌کند تا هر نویسنده (نه فقط چک‌این)
-- محافظت داشته باشد.
--
-- تصمیمِ مالک (۲۰۲۶-۰۹-۰۹): کلیدِ صریح، نه کلیدِ طبیعیِ
-- (user_id, restaurant_id, reason, note). دلیل: `note` متنِ آزادِ فارسی
-- است (مثلاً `کش‌بک رزرو ${code}` — reservations.ts:616)؛ یکتاییِ متکی به
-- متنی که هرکسی می‌تواند بی‌خبر ویرایش کند، همان کلاسِ نقصِ کلیدهایِ
-- override XSS است که به متنِ expression گره خورده بودند.
--
-- چرا `UNIQUE` سراسری و نه ایندکسِ جزئی (WHERE): در Postgres یک UNIQUE
-- معمولی رویِ ستونِ nullable خودش همین رفتار را می‌دهد — NULLها با هم
-- برابر شمرده نمی‌شوند، پس چند ردیفِ بی‌کلید مجازند و فقط مقادیرِ
-- غیرنال یکتا می‌مانند. نیازی به `WHERE idempotency_key IS NOT NULL`
-- نیست. **الگوی از قبل موجود در همین دیتابیس:** `jobs.idempotency_key`
-- دقیقاً همین‌طور تعریف شده (`jobs_idempotency_key_key`). ⚠️ نکته‌ی جانبی
-- که در همین بررسی پیدا شد: جدولِ jobs یک ایندکسِ **جزئیِ اضافه/زائد** هم
-- دارد (`idx_jobs_idem`, `WHERE idempotency_key IS NOT NULL`) که همان
-- تضمین را با هزینه‌ی نوشتنِ دوبرابر تکرار می‌کند — رگرسیونِ کوچکِ قدیمی،
-- خارج از دامنه‌ی همین migration، در گزارشِ PHASE1-LEDGER-EVIDENCE ثبت شد.
-- این migration عمداً از همان اشتباه تکرار نمی‌کند.
--
-- چرا nullable: هر نویسنده‌ای که رویدادش می‌تواند تکرار شود (retry، race،
-- cron دوباره) کلیدِ پایدار می‌سازد. نوشتنِ دستیِ/ادمینِ یک‌بارمصرف
-- (مثلاً `reason='adjustment'`) می‌تواند null بگذارد — هر فراخوانیِ آن
-- عمداً مستقل است، نه تکرارِ یک رویدادِ قبلی.
--
-- ⚠️ صداقتِ صریح دربابِ قدرتِ این قید: چون کلید **اختیاری** است (nullable،
-- nullها یکتا شمرده نمی‌شوند)، این یک قیدِ **داوطلبانه** است، نه اجباری —
-- اولین نویسنده‌ای که کلید ندهد بی‌صدا از آن رد می‌شود (insert با
-- idempotency_key=NULL همیشه موفق است). این migration فقط ستون/ایندکس را
-- می‌سازد؛ اجبارِ واقعی از کدِ نویسنده‌ها می‌آید (loyalty.ts، lifecycle.ts،
-- reservations.ts — رجوع کن به PHASE1-LEDGER-EVIDENCE.md برایِ فهرستِ
-- کاملِ نویسنده‌ها و اینکه کدام‌ها امروز کلید می‌دهند).
--
-- چرا نیازی به backfill نیست: ستون تازه است و همه‌ی ردیف‌هایِ موجود پیش از
-- این migration به‌طورِ طبیعی NULL می‌گیرند؛ چون NULL با NULL برابر شمرده
-- نمی‌شود، هیچ ردیفِ تاریخی با قید تداخل نمی‌کند و migration رویِ دیتایِ
-- واقعی/کثیف هم بدونِ dedup/reconciliationِ اضافه امن است.
--
-- اثباتِ falsifiability (ثبت‌شده در docs/audit/reports/PHASE1-LEDGER-EVIDENCE.md):
-- حذفِ موقتِ همین ایندکس → insertِ دوم با همان کلید موفق می‌شود (قرمز) →
-- بازگردانی → insertِ دوم P2002 می‌گیرد (سبز).
-- ═══════════════════════════════════════════════════════════════════════

ALTER TABLE points_ledger ADD COLUMN IF NOT EXISTS idempotency_key TEXT;

CREATE UNIQUE INDEX IF NOT EXISTS points_ledger_idempotency_key_key
  ON points_ledger (idempotency_key);
