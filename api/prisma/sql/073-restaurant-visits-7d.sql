-- ۰۷۳ — ستونِ visits_7d روی restaurants (رتبه‌بندیِ واقعیِ فیدِ «محبوب امشب»)
--
-- ⚠️ چرا: فیدِ اپِ مشتری عنوانِ «🔥 محبوب امشب» دارد، ولی ترتیبش از
-- `GET /api/v1/restaurants` می‌آمد که `orderBy: { id: 'desc' }` بود — و `id`
-- یک UUID است. یعنی ترتیب **پایدار** بود (که برایِ cursor لازم است) ولی هیچ
-- ربطی به محبوبیت نداشت؛ عملاً تصادفی.
--
-- نکته‌ی مهم: سیگنالِ واقعی از قبل در همان route حساب می‌شد و روی هر کارت هم
-- نمایش داده می‌شد (`visits7d` — رزروهایی که در ۷ روزِ گذشته به حضور رسیده‌اند).
-- فقط **بعد از** صفحه‌بندی اجرا می‌شد، پس نمی‌توانست مبنایِ مرتب‌سازی باشد.
-- یعنی محصول عددِ درست را داشت، نشانش هم می‌داد، ولی بر اساسش مرتب نمی‌کرد.
--
-- چرا ستونِ denormalized و نه `orderBy` روی رابطه: Prisma نمی‌تواند بر اساسِ
-- شمارشِ **فیلترشده‌ی** یک رابطه مرتب کند (`_count` فیلترِ where نمی‌گیرد)، و
-- صفحه‌بندیِ cursor به یک ترتیبِ قطعیِ ایندکس‌دار نیاز دارد.
--
-- ⚠️ تازگی، صادقانه: این ستون در جابِ شبانه‌ی `customer-insights` (۰۳:۰۰)
-- بازمحاسبه می‌شود، پس تا ۲۴ ساعت کهنه است. برایِ یک شمارشِ **۷ روزه‌ی
-- غلتان** این بی‌اهمیت است (عدد در طولِ یک روز جهش نمی‌کند)، ولی ادعای
-- «همین الان» نیست و نباید هم بشود.
-- ═══════════════════════════════════════════════════════════════════════

ALTER TABLE restaurants ADD COLUMN IF NOT EXISTS visits_7d integer NOT NULL DEFAULT 0;

-- ترتیبِ ایندکس دقیقاً همان ترتیبِ کوئریِ فهرستِ عمومی است:
-- فیلترِ is_open، سپس visits_7d نزولی، سپس id نزولی (شکنندهٔ تساوی و کلیدِ cursor).
CREATE INDEX IF NOT EXISTS restaurants_open_visits_idx
  ON restaurants (is_open, visits_7d DESC, id DESC);

-- مقداردهیِ اولیه تا فهرست از همان اولین استقرار معنادار باشد و منتظرِ
-- اولین cron نماند (وگرنه همه‌ی رستوران‌ها صفر می‌گیرند و ترتیب دوباره
-- عملاً بر اساسِ id می‌شود — یعنی همان باگ، فقط بی‌صدا).
UPDATE restaurants r
   SET visits_7d = COALESCE(v.c, 0)
  FROM (
    SELECT restaurant_id, COUNT(*)::int AS c
      FROM reservations
     WHERE status IN ('seated', 'dining', 'completed')
       AND slot_start >= now() - interval '7 days'
       AND slot_start <= now()
     GROUP BY restaurant_id
  ) v
 WHERE v.restaurant_id = r.id;
