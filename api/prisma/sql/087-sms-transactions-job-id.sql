--  ۰۸۷ — `sms_transactions.job_id` + ایندکسِ یکتا: هر job حداکثر یک کسرِ پیامک
--
--  چرا (دستورِ ۰۴۹ §۳): handlerِ `sms` در `worker.ts` پیش از تماس با
--  ارائه‌دهنده `consumeSms` می‌زد و هیچ کلیدِ یکتایی به‌ازای job نداشت. پس
--  هر اجرای دوباره‌ی همان job — retryِ پس از شکستِ شبکه، یا reclaimِ پس از
--  کرشِ worker (d64d84a) — یک اعتبارِ دیگر از رستوران کم می‌کرد. تا ۵ اعتبار
--  برای یک پیام، و `sms_total_sent` هم با هر تلاش بالا می‌رفت.
--
--  رفع در کد: چک ← ارسال ← کسر **فقط پس از پذیرشِ ارائه‌دهنده**، و کسر با
--  `job_id`. این ستون و ایندکس نیمه‌ی پایگاه‌داده‌ی همان رفع‌اند: حتی اگر دو
--  اجرای هم‌زمانِ یک job هر دو از پیش‌بررسیِ کد رد شوند، دومی روی همین
--  ایندکس `unique_violation` می‌گیرد و تراکنشش — با کسرِ موجودی‌اش — برمی‌گردد.
--
--  ⚠️ چرا ایندکسِ یکتای **ساده** و نه جزئی (`WHERE job_id IS NOT NULL`):
--  Postgres در ایندکسِ یکتا NULLها را متمایز می‌داند، پس شارژِ ادمین و مصرفِ
--  مسیرِ اضطراری (بدونِ job) هر تعداد که باشند با هم برخورد نمی‌کنند. و شکلِ
--  ساده همان چیزی است که `@unique`ِ Prisma می‌سازد — پس `db push`ِ CI و این
--  فایل یک ایندکس با یک نام می‌سازند (گارد: schema-drift.integration.test.mts).
--
--  ⚠️ FK به `jobs` عمداً گذاشته **نمی‌شود**: jobهای کامل‌شده پاک‌سازی می‌شوند،
--  ولی ردِ مالی نباید با پاک‌شدنِ صف پاک شود یا جلوی پاک‌سازی را بگیرد.
--
--  ستون nullable است و پیش‌فرض ندارد: ردیف‌های موجود واقعاً به jobی بسته
--  نبوده‌اند و نباید وانمود شود که بوده‌اند.
--
--  idempotent.
-- ═══════════════════════════════════════════════════════════════════════

ALTER TABLE sms_transactions
  ADD COLUMN IF NOT EXISTS job_id UUID;

CREATE UNIQUE INDEX IF NOT EXISTS sms_transactions_job_id_key
  ON sms_transactions (job_id);
