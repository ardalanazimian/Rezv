--  ۰۴۷ — دسته‌بندیِ آیتمِ منو (پیش‌نیازِ CRUDِ منو در پنلِ بیزنس)
--
--  تا این migration، مدلِ MenuItem وجود داشت ولی هیچ روتی برایِ ساخت/ویرایش/
--  حذفش نبود؛ تنها جایی که ردیف درج می‌کرد prisma/seed.ts بود. یعنی رستورانِ
--  واقعی برایِ همیشه منوی خالی داشت — و چون تنها منبعِ مبلغ در رزرونو
--  پیش‌سفارش از منوست، کلِ زنجیره‌ی پیش‌سفارش→مبلغ→CLV مرده بود
--  (رجوع کن به migration ۰۴۶ و ممیزیِ ۲۰۲۶-۰۸-۱۹).
--
--  `category` عمداً nullable و متنِ آزاد است، نه enum: دسته‌بندیِ منو تصمیمِ
--  خودِ رستوران است («سرد/گرم»، «ایرانی/فرنگی»، …) و enum کردنش یعنی هر
--  رستورانِ تازه باید منتظرِ deploy بماند. NULL = دسته‌بندی‌نشده.
--
--  ایمنیِ تولید: ADD COLUMN با پیش‌فرضِ NULL در Postgres ۱۱+ بدونِ بازنویسیِ
--  جدول و با قفلِ کوتاه انجام می‌شود.
-- ═══════════════════════════════════════════════════════════════════════

ALTER TABLE menu_items ADD COLUMN IF NOT EXISTS category text;

-- کوئریِ پنل: آیتم‌هایِ یک رستوران به‌ترتیبِ دسته. (ایندکسِ
-- (restaurant_id, is_active) از قبل هست و مسیرِ عمومی را پوشش می‌دهد.)
CREATE INDEX IF NOT EXISTS menu_items_restaurant_category_idx
  ON menu_items (restaurant_id, category);
