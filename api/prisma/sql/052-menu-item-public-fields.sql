--  ۰۵۲ — فیلدهایِ لازمِ منویِ عمومی/QR رویِ menu_items
--
--  چرا: منویِ عمومی (اسکنِ QR سرِ میز + بخشِ منو در صفحه‌ی SEO) به سه چیز
--  نیاز دارد که مدل اصلاً نداشت:
--    • description — یک خطِ توضیح («با سسِ قارچ و برنجِ ایرانی»). بدونِ آن
--      کارتِ آیتم فقط نام و قیمت است و از منویِ کاغذی هم کم‌تر می‌گوید.
--    • image_url   — عکسِ غذا. مهم‌ترین محرکِ انتخاب سرِ میز، و در JSON-LD
--      هم فیلدِ image رویِ MenuItem را پر می‌کند (سیگنالِ غنی برایِ گوگل).
--    • sort_order  — ترتیبِ دلخواهِ رستوران‌دار. تا امروز منویِ عمومی با
--      `ORDER BY sold_count DESC` مرتب می‌شد، یعنی ترتیبِ منو را آمارِ فروش
--      تعیین می‌کرد نه خودِ رستوران — برایِ گزارشِ پرفروش‌ها درست است، برایِ
--      نمایشِ منو نه (پیش‌غذا باید قبلِ دسر بیاید، نه بعدش چون کم‌تر فروخته).
--
--  چرا در همین جدول و نه جدولِ تازه: منبعِ حقیقتِ منو یکی است (MenuItem) و
--  پنلِ بیزنس هم همان را ویرایش می‌کند. جدولِ دومِ «منویِ عمومی» یعنی دو
--  نسخه که از هم می‌افتند.
--
--  ایمنیِ تولید: هر سه ستون nullable/دارایِ DEFAULT ثابت‌اند، پس ADD COLUMN
--  در Postgres 11+ جدول را بازنویسی نمی‌کند و فقط قفلِ کوتاه می‌گیرد.
--  هیچ backfillی لازم نیست: NULL یعنی «رستوران‌دار هنوز پرش نکرده» و UI
--  همان‌جا حالتِ بدونِ‌توضیح/بدونِ‌عکس را نشان می‌دهد. sort_order پیش‌فرضِ ۰
--  می‌گیرد و مرتب‌سازی به نام fallback می‌کند، پس ترتیبِ فعلی نمی‌شکند.
--
--  idempotent (IF NOT EXISTS) — مطابقِ بقیه‌ی مهاجرت‌هایِ این پوشه.
-- ═══════════════════════════════════════════════════════════════════════

ALTER TABLE menu_items ADD COLUMN IF NOT EXISTS description TEXT;
ALTER TABLE menu_items ADD COLUMN IF NOT EXISTS image_url   TEXT;
ALTER TABLE menu_items ADD COLUMN IF NOT EXISTS sort_order  INTEGER NOT NULL DEFAULT 0;

-- کوئریِ داغِ منویِ عمومی: «آیتم‌هایِ فعالِ این رستوران، به ترتیبِ نمایش».
-- ایندکسِ موجود (restaurant_id, is_active) بخشِ WHERE را پوشش می‌دهد ولی
-- مرتب‌سازی را نه؛ این ایندکس هر دو را با هم می‌دهد تا صفحه‌ی QR نیازی به
-- sort نداشته باشد.
CREATE INDEX IF NOT EXISTS menu_items_public_order_idx
  ON menu_items (restaurant_id, is_active, sort_order, name);
