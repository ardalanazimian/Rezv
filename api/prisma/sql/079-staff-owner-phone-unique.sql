-- ۰۷۹ — یکتاییِ سراسریِ شماره در نقشِ owner (بستنِ raceِ بازِ SPEC-B)
--
-- چرا ایندکسِ جزئی و نه «چکِ داخلِ تراکنش»: هر دو مسیرِ سازنده‌ی owner
-- (provisionBusiness در lib/provisioning.ts و createTrialAccount در
-- lib/site-orders.ts) الگوی TOCTOU دارند — SELECTِ چکِ تکراری بیرون/قبلِ
-- INSERT است و زیرِ READ COMMITTED دو تراکنشِ هم‌زمان هیچ‌کدام ردیفِ
-- commit‌نشده‌ی دیگری را نمی‌بینند؛ جابه‌جاکردنِ همان SELECT به داخلِ
-- تراکنش پنجره را نمی‌بندد. تنها لایه‌ای که می‌تواند نویسنده‌های هم‌زمان را
-- سریالیزه کند خودِ DB است: بازنده‌ی race روی همین ایندکس unique_violation
-- می‌گیرد، کلِ تراکنشش (Tenant→Restaurant→Staff→Invite) رول‌بک می‌شود و
-- هیچ یتیمی نمی‌ماند. کد آن خطا (P2002) را به همان پاسخِ تمیزِ مسیرِ
-- ترتیبی نگاشت می‌کند (duplicate_owner_phone / پیامِ trial).
--
-- چرا فقط role='owner' و نه کلِ phone: تکرارِ شماره‌ی یک «کارمند» بینِ
-- تنانت‌های مختلف امروز قانونی است (@@unique([tenantId, phone]) فقط
-- درون‌تنانتی است و ورودِ کارکنان با قاعده‌ی «قدیمی‌ترین ثبت برنده» از
-- مهاجرتِ ۰۷۲ resolve می‌شود). ownerِ دوم با شماره‌ی تکراری اما همیشه
-- حسابِ مرده می‌سازد (هرگز نمی‌تواند با OTP وارد شود) — همان دلیلی که
-- چکِ appسطحِ SPEC-B (§۶-۵) از اول رد می‌کرد؛ این ایندکس همان قاعده را
-- در برابر هم‌زمانی هم قطعی می‌کند. raceِ باقی‌مانده‌ی «owner+کارمند با
-- یک شماره، هم‌زمان، در دو تنانت» عمداً پوشش داده نمی‌شود: بستنش یکتاییِ
-- سراسریِ phone می‌خواهد که featureِ قانونیِ بالا را می‌شکند.
--
-- ⚠️ Prisma ایندکسِ جزئی (WHERE) را در schema نمی‌تواند بیان کند؛ طبقِ
-- الگوی مصوبِ گاردِ drift (schema-drift.integration.test.mts) این ایندکس
-- به فهرستِ required اضافه شده و DROPش در ACCEPTED_DRIFT پذیرفته شده است.
-- در schema.prisma فقط با کامنت روی مدلِ Staff مستند است.
--
-- روی دیتای کثیف (دو ownerِ هم‌شماره از قبل): CREATE UNIQUE INDEX با پیامِ
-- روشنِ «Key (phone)=(…) is duplicated» بلند شکست می‌خورد — عمدی است؛
-- پاک‌سازیِ خودکارِ حسابِ مردمی در migration ممنوع (ممکن است ownerِ دوم
-- اعتبارنامه‌ی username/password از ۰۷۴ داشته باشد). اپراتور باید تکلیفِ
-- ردیف‌های تکراری را آگاهانه روشن کند، بعد دوباره اجرا کند (idempotent).
--
-- 🚨 پیش‌نیازِ اجباریِ deploy (دستورِ مالک، ۲۰۲۶-۰۸-۲۷): پیش از اعمالِ این
-- فایل روی «هر» محیطِ واقعی (production/staging)، این کوئری باید اجرا و
-- خالی‌بودنش ثبت شود:
--   SELECT phone, count(*), array_agg(id ORDER BY created_at)
--   FROM staff WHERE role='owner'
--   GROUP BY phone HAVING count(*) > 1;
-- اگر خالی نبود: هیچ حذف/ادغامِ خودکاری مجاز نیست — فهرست برای تصمیمِ مالک
-- می‌رود و یک اسکریپتِ reconciliationِ جداگانه (پیش از ۰۷۹) نوشته می‌شود.
-- نتیجه‌ی ثبت‌شده تا این تاریخ (docs/reports/PRE-MERGE-VERIFY-2026-08-27.md):
-- هر دو DB قابل‌دسترسِ توسعه (تستِ 55432 و استکِ محلیِ compose) صفر ردیف؛
-- محیطِ production/staging مستقر خارج از این ماشین یافت نشد — اگر/وقتی
-- ساخته شد، همین پیش‌نیاز برقرار است. (seed غیرidempotent است و اجرای
-- دوباره‌اش پس از ۰۷۹ به‌جای slug حالا زودتر و روی همین ایندکس می‌میرد —
-- همان کلاسِ tolerated در docker-entrypoint؛ نصبِ تازه امن است چون دو
-- ownerِ seed شماره‌ی متمایز دارند.)
--
-- ⚠️ نبودِ شرطِ is_active در predicate **عمدی** است (تأییدِ بازبینیِ ۰۸-۲۷)،
-- نه سهو — دو دلیلِ ساختاری:
--   ۱) resolutionِ ورود (findStaffForLogin) قاعده‌ی «قدیمی‌ترین ثبت برنده»
--      را **بدونِ** فیلترِ isActive اجرا می‌کند (staff-helpers.ts) و بعد
--      ردیفِ غیرفعال را رد می‌کند (auth/staff/verify:42-44) — یعنی ownerِ
--      جدیدی که شماره‌اش با ردیفِ غیرفعالِ قدیمی‌تر مشترک باشد هرگز
--      نمی‌تواند وارد شود؛ مجازکردنِ ساختش یعنی تولیدِ حسابِ مرده.
--   ۲) predicateِ «AND is_active» خودِ reactivation (is_active=false→true)
--      را به یک مسیرِ نقضِ تازه و نگاشت‌نشده تبدیل می‌کرد.
-- پیامد: شماره‌ی ownerِ یک رستورانِ offboard/غیرفعال تا آزادسازیِ دستی قفل
-- می‌ماند. مسیرِ آزادسازی (عملیاتِ اپراتورِ پلتفرم، فعلاً بدونِ route):
-- تغییر/آزادکردنِ phoneِ ردیفِ قدیمی یا حذفِ خودِ ردیف. توجه: demote به
-- 'staff' فقط ایندکس را آزاد می‌کند نه چک‌های appسطح را (آن‌ها هر ردیفِ
-- staff با آن شماره را می‌بینند) — پس آزادسازیِ کامل = phone یا حذف.
-- ═══════════════════════════════════════════════════════════════════════

CREATE UNIQUE INDEX IF NOT EXISTS staff_owner_phone_unique_idx
  ON staff (phone) WHERE role = 'owner';
