--  047 — ایندکسِ هرسِ platform_events (فازِ ۲، پروتکل §۱۴)
--
--  زمینه: جدولِ platform_events تا امروز **هیچ سیاستِ نگه‌داری‌ای** نداشت و
--  بی‌مرز رشد می‌کرد. این در `docs/architecture/AI-DATA-ELIGIBILITY.md` §۳
--  به‌عنوانِ «کارِ باز» ثبت شده بود؛ این migration نیمه‌ی دیتابیسیِ آن است.
--
--  چرا ingested_at و نه occurred_at:
--    occurred_at از کلاینت می‌آید (کلمپ‌شده به بازه‌ی [−۳۰ روز, +۵ دقیقه]).
--    اگر هرس روی آن انجام می‌شد، یک کلاینتِ بدخواه می‌توانست با backdate کردنِ
--    رویداد، حذفِ **زودهنگامِ** آن را تحریک کند — یعنی پاک‌کردنِ ردِ خودش.
--    ingested_at حقیقتِ سروری است (DEFAULT now() در لحظه‌ی درج).
--
--  چرا composite با trust_level:
--    سیاستِ نگه‌داری بر اساسِ سطحِ اعتماد تفکیک می‌شود (رویدادِ SERVER_VERIFIED
--    تنها موادِ خامِ واجدِ شرایطِ آموزش است و باید بیشتر بماند؛ ANONYMOUS_CLIENT
--    فقط برایِ آمارِ تجمیعی است و زودتر می‌رود). کوئریِ هرس دقیقاً
--    `WHERE trust_level = $1 AND ingested_at < $2` است، پس همین composite
--    بدونِ هیچ ایندکسِ اضافه‌ای کاملاً پوششش می‌دهد.
--
--  ⚠️ ایندکسِ موجودِ platform_events_trust_level_idx (trust_level, occurred_at)
--     از migration 046 حذف نمی‌شود — آن برایِ *خواندنِ* واجدِ شرایط‌ها به‌کار
--     می‌رود (occurred_at زمانِ رفتارِ کاربر است)، این‌یکی برایِ *هرس*.
-- ═══════════════════════════════════════════════════════════════════════

CREATE INDEX IF NOT EXISTS platform_events_trust_ingested_idx
  ON platform_events (trust_level, ingested_at);
