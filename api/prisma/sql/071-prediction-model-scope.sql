-- ═══════════════════════════════════════════════════════════════════════
--  دامنه‌ی مدل روی دفترِ پیش‌بینی — بستنِ حلقه‌ی سنجشِ مدلِ سراسری
--
--  ⚠️ شکافی که می‌بندد (ممیزیِ نهاییِ ۲۰۲۶-۰۸-۲۵):
--  مدلِ سراسری از دیروز به **هر** رستورانی که مدلِ اختصاصی ندارد سرو
--  می‌شود — یعنی همه‌ی رستوران‌های تازه، دقیقاً همان‌هایی که برایشان ساخته
--  شد. ولی هیچ راهی برای سنجشش در تولید نبود:
--
--   • `getEffectiveNoShowModel` برای سراسری `runId: null` می‌دهد، پس
--     پیش‌بینی با `model_run_id = NULL` ثبت می‌شود.
--   • `detectPerformanceDrift` روی `p.model_run_id = <activeRunId>` فیلتر
--     می‌کند ⇒ پیش‌بینی‌های سراسری **هرگز** شمرده نمی‌شوند.
--   • `rollbackDriftedModel` فقط `restaurant_no_show_models` را می‌نویسد ⇒
--     **هیچ مسیری مدلِ سراسریِ خراب را غیرفعال نمی‌کرد.**
--   • و در آمارِ دقت، پیش‌بینی‌های سراسری با سطلِ «مدل‌های بدونِ نسب‌نامه»
--     (پیش از مهاجرتِ ۰۵۶) قاطی می‌شدند.
--
--  خودِ کد این باگ را **دقیقاً توصیف کرده بود**: کامنتِ فیلدِ `modelScope`
--  در `lib/customer-insights.ts` می‌گوید بدونش «null یعنی heuristic» با
--  «null یعنی سراسری» قاطی می‌شود و دقتِ تولید به دامنه‌ی اشتباه نسبت داده
--  می‌شود. آن فیلد ساخته شد ولی هرگز به دفتر نرسید.
--
--  مقدارها: 'restaurant' | 'platform' | 'heuristic'.
--  ⚠️ پیش‌فرض عمداً NULL است، نه یک مقدارِ حدسی: ردیف‌های قبل از این
--  مهاجرت واقعاً **نامعلوم**اند. جعلِ 'restaurant' برایشان یعنی همان
--  «صفر به‌جای نامعلوم» که ML_CONTRACT ممنوع کرده.
-- ═══════════════════════════════════════════════════════════════════════

ALTER TABLE model_predictions
  ADD COLUMN IF NOT EXISTS model_scope TEXT;

-- سنجشِ دقتِ مدلِ سراسری = «همه‌ی پیش‌بینی‌های scope=platform در بازه» —
-- بدونِ ایندکس یک اسکنِ کاملِ جدولِ پرترافیک است.
--
-- ⚠️ عمداً **partial نیست** (بدونِ WHERE): Prisma ایندکسِ جزئی را نمی‌تواند
-- بیان کند، و طبقِ قاعده‌ی CLAUDE.md هر ایندکس باید هم در schema.prisma
-- باشد هم در مهاجرتِ SQL — وگرنه یا `db push` حذفش می‌کند یا یک ایندکسِ
-- تکراری با نامِ دیگر ساخته می‌شود. صرفه‌جوییِ نسخه‌ی جزئی هم ناچیز بود،
-- چون از این به بعد تقریباً همه‌ی ردیف‌ها مقدار دارند.
CREATE INDEX IF NOT EXISTS model_predictions_scope_generated_idx
  ON model_predictions (model_scope, generated_at DESC);
