--  چرا لازم شد: اپِ مشتری در پروفایل صریحاً وعده می‌دهد «قبل از رزروت یادت
--  می‌ندازیم» و «یادآوری‌ها پیامکی می‌آید»
--  (apps/customer/js/user-profile.js:17,87,104) — ولی در کلِ کدبیس **هیچ**
--  `enqueueSms({template:'reminder'})` وجود نداشت. قالبِ `rezervno-reminder`
--  از روزِ اول در TEMPLATE_MAP بود و هرگز صدا زده نمی‌شد. یعنی یک وعده‌ی
--  اعلام‌شده که هیچ‌وقت تحویل نمی‌شد.
--
--  چرا ستون و نه فقط idempotencyKeyِ صف: جدولِ `jobs` سیاستِ نگهداریِ ۷ روزه
--  دارد (maintenance/retention) — بعد از پاک‌سازی، کلیدِ dedup از بین می‌رود.
--  ضمناً این ستون **قابلِ کوئری** است: «آیا این رزرو یادآوری‌اش را گرفت؟»
--  یک پرسشِ عملیاتیِ واقعی است که با صفِ پاک‌شده جواب داده نمی‌شود.
--  هر دو لایه با هم به‌کار می‌روند (ستون + idempotencyKey) — دفاع در عمق.
--
--  ایندکسِ جزئی: کوئریِ cron فقط رزروهای «هنوز یادآوری‌نشده»ی نزدیک را
--  می‌خواهد. ایندکسِ جزئی روی همان شرط، جدول را با رشدِ رزروهای گذشته
--  کند نمی‌کند — و چون شرطش با کوئری یکی است، planner واقعاً استفاده‌اش
--  می‌کند (نه فقط «وجود دارد»).
--
--  ⚠️ نامِ ایندکس عمداً همانی است که Prisma برای `@@index` تولید می‌کند تا
--  `db push` نسخه‌ی دومِ هم‌ارز با نامِ دیگر نسازد (درسِ مهاجرتِ ۰۶۶).
-- ═══════════════════════════════════════════════════════════════════════

ALTER TABLE "reservations"
  ADD COLUMN IF NOT EXISTS "reminder_sent_at" TIMESTAMP(3);

CREATE INDEX IF NOT EXISTS "reservations_slot_start_reminder_sent_at_idx"
  ON "reservations" ("slot_start", "reminder_sent_at");
