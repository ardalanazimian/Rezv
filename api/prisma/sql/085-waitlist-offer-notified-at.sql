--  ۰۸۵ — `waitlist_entries.offer_notified_at`
--
--  چرا: امروز هیچ‌چیز روی خودِ ردیف ثبت نمی‌کند که آیا مهمان از آفر
--  **خبردار شد** یا نه. `offered_at` می‌گوید آفر کِی **داده شد**، نه اینکه
--  رسید. نتیجه‌اش این است که دو ردیفِ زیر بایت‌به‌بایت یکی‌اند:
--
--    • مهمانی که پیام گرفت و جواب نداد.
--    • مهمانی که **هیچ کانالی برایش dispatch نشد** و طبعاً جواب نداد.
--
--  و `expireOffers` هر دو را `no_response` می‌کند — یعنی دومی به‌خاطرِ
--  پیامی که هرگز فرستاده نشد، «بی‌پاسخ» ثبت می‌شود.
--
--  ⚠️ حالتِ «صفر کانال» فرضی نیست، اندازه‌گیری شد (۲۰۲۶-۰۹-۱۰):
--    `notifyEntry` (waitlist.ts:973-1005) هر سه کانال را شرطی می‌فرستد —
--      SMS   نیاز دارد به `notifySms && guestPhone`، و برای `offered`
--            از گیتِ رضایتِ `availability` هم رد شود
--      Push  نیاز دارد به `notifyPush && userId`
--      Email نیاز دارد به `notifyEmail && guestEmail`
--    و در اسکیما: `guest_phone` و `guest_email` هر دو nullable، `user_id`
--    برای ورودیِ مهمان null، و `notify_email` پیش‌فرض **false**.
--    `joinWaitlist` هم تلفن را اجباری نمی‌کند (`input.guest?.phone ?? null`).
--    پس یک مهمانِ بدونِ حساب که تلفن نداده — یا رضایتِ availability را
--    خاموش کرده — **هیچ کانالی ندارد**.
--
--  ⚠️ و آنچه این ستون **نمی‌گوید**: اینکه پیام واقعاً **تحویل** شد. آن را
--  این لایه نمی‌تواند بداند و عمداً هم نباید تظاهر کند: `enqueueSms`،
--  `queuePush` و `queueEmail` هر سه به‌طورِ طراحی‌شده هرگز reject نمی‌کنند
--  (`sms.ts:147-178` صریح می‌نویسد چرا: throwِ تازه یعنی رزروِ ثبت‌شده با
--  ۵۰۰ گزارش شود). شکستِ واقعیِ ارسال در لایه‌ی خودش شمرده می‌شود
--  (`rezervno_sms_failed_total{template,reason}`).
--
--  پس معنایِ دقیقِ این ستون: **«دستِ‌کم یک کانال واقعاً dispatch شد.»**
--  نه بیشتر. NULL یعنی «هیچ کانالی نرفت» — و آن، برخلافِ تحویل، از همین
--  لایه قابلِ دانستن است.
--
--  ستون nullable است و پیش‌فرض ندارد: ردیف‌های موجود واقعاً نامعلوم‌اند و
--  «نامعلوم» نباید به «خبردار شد» یا «خبردار نشد» تبدیل شود.
--
--  ایندکس عمداً ساخته **نمی‌شود**: تنها مصرف‌کننده‌اش `expireOffers` است که
--  از قبل روی `(status, offer_expires_at)` فیلتر می‌کند و مجموعه‌ی نتیجه
--  کوچک است؛ یک ایندکسِ بی‌مصرف فقط هزینه‌ی نوشتن اضافه می‌کند.
--
--  idempotent.
-- ═══════════════════════════════════════════════════════════════════════

ALTER TABLE waitlist_entries
  ADD COLUMN IF NOT EXISTS offer_notified_at TIMESTAMPTZ;
