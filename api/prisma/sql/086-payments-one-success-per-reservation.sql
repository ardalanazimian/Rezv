-- ۰۸۶ — حداکثر **یک** پرداختِ موفق به‌ازای هر رزرو
--
-- چرا: `payments` عمداً چند ردیف به‌ازای یک رزرو دارد (کامنتِ مدلِ
-- Reservation: «یک رزرو می‌تواند چند تلاش پرداخت داشته باشد») و تا امروز
-- هیچ‌چیز در سطحِ DB نمی‌گفت که فقط **یکی** از آن‌ها حق دارد `success` شود.
--
-- مسیرِ واقعیِ نقض (نه فرضی — از خواندنِ دو روت کنارِ هم درمی‌آید):
--   ۱. کاربر `POST /reservations/:code/pay` می‌زند → authorityِ A، ردیفِ pending.
--   ۲. در درگاه معطل می‌ماند و دوباره «پرداخت» را می‌زند → همان روت
--      (reservations/[code]/pay) ردیفِ A را `failed`/«جایگزین‌شده» می‌کند و
--      authorityِ B می‌سازد. ولی **A در زرین‌پال هنوز زنده است**.
--   ۳. کاربر B را تمام می‌کند → callback → رزرو `deposit_status='paid'`.
--   ۴. بعد A را هم تمام می‌کند → callback با authorityِ A. تنها خروجِ
--      زودهنگامِ آن روت `payment.status === 'success'` بود و A الان `failed`
--      است ⇒ رد می‌شد، verify می‌کرد، و دوباره `paid` می‌نوشت.
--   نتیجه: دو پرداختِ موفقِ واقعی برای یک رزرو. پولِ مهمان دوبار کم می‌شود.
--
-- گاردِ اپلیکیشنی همین امروز اضافه شد (قفلِ `SELECT … FOR UPDATE` روی ردیفِ
-- رزرو داخلِ تراکنشِ callback + بازخوانیِ `deposit_status`). این فایل ضامنِ
-- **دومِ** ساختاری است، دقیقاً به همان دلیلی که ۰۸۱ برای دفترِ امتیاز نوشته
-- شد: قفلِ اپلیکیشنی فقط نویسنده‌هایی را سریالیزه می‌کند که از همان مسیر رد
-- شوند؛ هر نویسنده‌ی آینده (اسکریپتِ reconciliation، webhookِ تازه‌ی درگاه،
-- روتِ عودت) بدونِ این ایندکس دوباره همان حالت را می‌سازد.
--
-- چرا ایندکسِ **جزئی** و نه `UNIQUE(reservation_id)`: تلاش‌های `pending` و
-- `failed` باید آزادانه تکرار شوند (همان قابلیتِ «تلاشِ دوباره‌ی پرداخت»)؛
-- فقط `success` است که باید یکتا بماند. `refunded` هم عمداً بیرونِ predicate
-- است: یک پرداختِ عودت‌شده دیگر اعتبارِ زنده نیست و رزرو باید بتواند پرداختِ
-- تازه‌ی موفق بگیرد.
--
-- ⚠️ CONCURRENTLY عمداً **نیست** — همان دلیلِ ثبت‌شده در ۰۶۶ و ۰۰۱:
-- `prisma/apply-sql.sh` هر فایل را با `prisma db execute` اجرا می‌کند و آن
-- فایل را در یک تراکنشِ ضمنی می‌گذارد؛ `CREATE INDEX CONCURRENTLY` داخلِ
-- تراکنش کار نمی‌کند و کلِ بوتِ کانتینر را می‌شکست (apply-sql.sh روی خطا
-- `exit 1` می‌کند). رویِ یک جدولِ `payments`ِ بزرگ و زنده، اپراتور می‌تواند
-- **پیش از** استقرار همین ایندکس را دستی و بدونِ قفل بسازد و بعد این فایل
-- به‌خاطرِ `IF NOT EXISTS` بی‌اثر رد می‌شود:
--   psql "$DATABASE_URL" -c "CREATE UNIQUE INDEX CONCURRENTLY IF NOT EXISTS \
--     payments_one_success_per_reservation ON payments(reservation_id) \
--     WHERE status = 'success';"
--
-- 🚨 پیش‌نیازِ اجباریِ deploy (همان قاعده‌ی ۰۷۹): رویِ هر محیطِ واقعی، پیش از
-- اعمال، این کوئری باید اجرا و خالی‌بودنش ثبت شود —
--   SELECT reservation_id, count(*), array_agg(id ORDER BY created_at)
--   FROM payments WHERE status = 'success'
--   GROUP BY reservation_id HAVING count(*) > 1;
-- اگر خالی نبود یعنی همین باگ قبلاً رخ داده و **پولِ واقعیِ کسی دوبار کم
-- شده**. هیچ اصلاحِ خودکاری اینجا مجاز نیست: ردیف‌های اضافه باید ابتدا در
-- درگاه عودت و سپس دستی به `refunded` تغییر کنند، بعد این فایل دوباره اجرا
-- شود (idempotent).
--
-- ⚠️ Prisma ایندکسِ جزئی (WHERE) را در schema نمی‌تواند بیان کند؛ طبقِ الگویِ
-- مصوبِ ۰۷۹ این ایندکس به فهرستِ required در
-- `tests/schema-drift.integration.test.mts` اضافه شده و DROPش در
-- ACCEPTED_DRIFT پذیرفته شده است. در schema.prisma فقط با کامنت روی مدلِ
-- Payment مستند است.
-- ═══════════════════════════════════════════════════════════════════════

CREATE UNIQUE INDEX IF NOT EXISTS payments_one_success_per_reservation
  ON payments (reservation_id) WHERE status = 'success';
