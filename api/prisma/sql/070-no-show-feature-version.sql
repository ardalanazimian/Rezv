-- ═══════════════════════════════════════════════════════════════════════
--  نسخه‌ی بردارِ ویژگی روی مدل‌های no-show
--
--  ⚠️ چرا لازم است — یک خرابیِ کاملاً خاموش:
--  `dot(weights, x)` در lib/ml-core.ts روی **طولِ weights** حلقه می‌زند.
--  اگر روزی یک ویژگی به بردار اضافه شود، مدلِ ذخیره‌شده‌ی قدیمی (۷ وزن) روی
--  بردارِ جدید (۹ ویژگی) هیچ خطایی نمی‌دهد — فقط دو ویژگیِ آخر را نادیده
--  می‌گیرد و یک امتیازِ **قابلِ‌باور ولی غلط** برمی‌گرداند. جهتِ برعکس بدتر
--  است: وزنِ ۹تایی روی بردارِ ۷تایی به `undefined` می‌رسد ⇒ NaN ⇒
--  `sigmoid(NaN)` ⇒ NaN، که تا خودِ UI می‌رود.
--
--  با این ستون، مدلی که نسخه‌اش با کدِ فعلی نمی‌خواند **سرو نمی‌شود** و
--  سیستم صادقانه به heuristic/مدلِ سراسری برمی‌گردد تا آموزشِ شبانه‌ی بعدی
--  نسخه‌ی تازه را بسازد.
--
--  مقدارِ پیش‌فرض `v1` عمدی است: همه‌ی ردیف‌های موجود دقیقاً همان بردارِ ۷
--  ویژگیِ اولیه را دارند، پس برچسبِ درستشان همین است — نه NULL که بعداً
--  «نمی‌دانم» را با «سازگار» قاطی کند.
-- ═══════════════════════════════════════════════════════════════════════

ALTER TABLE restaurant_no_show_models
  ADD COLUMN IF NOT EXISTS feature_version TEXT NOT NULL DEFAULT 'v1';

ALTER TABLE platform_no_show_models
  ADD COLUMN IF NOT EXISTS feature_version TEXT NOT NULL DEFAULT 'v1';

-- ⚠️ و حالا پیش‌فرض برداشته می‌شود — عمدی و مهم (جهش‌آزمایی ثابتش کرد):
-- تا وقتی پیش‌فرضِ DB برابرِ ثابتِ کد است، «مهرزدنِ نسخه توسطِ نویسنده» یک
-- کارِ بی‌اثر است و **هیچ تستی نمی‌تواند نبودش را بگیرد** (برداشتنِ هر سه
-- مهر ۰ تست را قرمز کرد). خطر آن‌جا ظاهر می‌شود که کسی ثابتِ کد را به `v2`
-- ببرد و مهرزدن را جا بیندازد: ردیف با `v1` نوشته می‌شود، گاردِ نسخه ردش
-- می‌کند، و مدل **هرگز سرو نمی‌شود** — سیستم بی‌صدا برای همیشه روی
-- heuristic می‌ماند.
--
-- بدونِ پیش‌فرض، همان اشتباه یک خطای بلندِ NOT NULL در همان اجرای آموزش
-- است. ردیف‌های موجود دستِ‌نخورده می‌مانند: مقدارشان هنگامِ ADD COLUMN
-- واقعاً نوشته شده، نه اینکه به پیش‌فرض ارجاع دهند.
ALTER TABLE restaurant_no_show_models ALTER COLUMN feature_version DROP DEFAULT;
ALTER TABLE platform_no_show_models   ALTER COLUMN feature_version DROP DEFAULT;

-- خواندنِ «آخرین مدلِ سراسریِ فعالِ **سازگار**» باید با ایندکس بخورد، نه با
-- اسکنِ کامل و فیلترِ بعدی.
CREATE INDEX IF NOT EXISTS platform_no_show_models_active_version_idx
  ON platform_no_show_models (is_active, feature_version, trained_at DESC);
