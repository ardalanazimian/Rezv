-- ۰۷۲ — ستونِ created_at روی staff
--
-- ⚠️ چرا: هایجکِ تنانت از راهِ `findFirst` بدونِ ترتیب.
--
-- `staff` کلیدِ یکتایِ `(tenant_id, phone)` دارد، یعنی یک شماره می‌تواند در
-- **چند** تنانت کارمند باشد. ولی مسیرِ ورودِ کارکنان
-- (`auth/staff/request` و `auth/staff/verify`) این را می‌زد:
--
--     db.staff.findFirst({ where: { phone: normalized } })
--
-- بدونِ tenant و بدونِ `orderBy`. Postgres در این حالت هیچ ترتیبی تضمین
-- نمی‌کند — نتیجه به ترتیبِ فیزیکیِ ردیف‌ها در heap گره می‌خورد.
--
-- مسیرِ حمله (بازتولیدشده روی همین دیتابیس):
--   ۱. مهاجم شماره‌ی قربانی را در تنانتِ **خودش** به‌عنوان کارمند ثبت می‌کند
--      (`POST /v1/restaurant/staff` هیچ اثباتِ مالکیتِ شماره نمی‌خواهد).
--   ۲. یک کارِ کاملاً عادیِ خودِ قربانی — مثلاً ویرایشِ نامش در پنل — یک
--      UPDATE می‌زند و ردیفِ قربانی به انتهای heap می‌رود.
--   ۳. از آن لحظه `findFirst` ردیفِ **مهاجم** را برمی‌گرداند: قربانی با
--      نقشِ تنزل‌یافته واردِ تنانتِ مهاجم می‌شود و از رستورانِ خودش قطع
--      می‌شود.
--
-- چرا رفعش ستونِ تازه می‌خواست: قاعده‌ی درست «قدیمی‌ترین ثبت برنده است»
-- می‌باشد، ولی این جدول هیچ ستونِ زمانی نداشت. سه راهِ بدونِ اسکیما هر سه
-- بد بودند: `orderBy: {id}` قطعی است ولی UUIDِ تصادفی یعنی ۵۰٪ هایجک با
-- ظاهرِ قطعی؛ fail-closed روی چند-تطبیق یک DoS می‌سازد (هر مالکی می‌تواند
-- هر کارمندی را با دانستنِ شماره‌اش برای همیشه قفل کند)؛ و حدس‌زدن ممنوع.
--
-- ⚠️ محدودیتِ صادقانه‌ی این مهاجرت: ردیف‌های **موجود** همگی `now()` یکسان
-- می‌گیرند، پس بینِ خودشان هنوز گره‌خورده‌اند. برای همین مرتب‌سازی در کد
-- دو کلیده است (`created_at ASC, id ASC`) تا دستِ‌کم **قطعی** باشد. آنچه
-- این مهاجرت واقعاً می‌بندد حالتِ مهمِ حمله است: هر ثبتِ **تازه** بعد از
-- این نقطه، زمانِ بزرگ‌تری می‌گیرد و هرگز نمی‌تواند از ردیفِ قدیمیِ قربانی
-- جلو بزند.
-- ═══════════════════════════════════════════════════════════════════════

ALTER TABLE staff ADD COLUMN IF NOT EXISTS created_at timestamptz NOT NULL DEFAULT now();

-- مسیرِ ورود روی (phone) فیلتر و روی (created_at, id) مرتب می‌کند.
CREATE INDEX IF NOT EXISTS staff_phone_created_idx ON staff (phone, created_at, id);
