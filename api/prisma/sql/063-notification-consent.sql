--  050 — رضایتِ اعلان‌رسانی (پروتکل §۱۳ «communication preferences» و §۱۷ «consent»)
--
--  مسئله‌ی واقعی (ممیزیِ ۲۰۲۶-۰۸-۲۴، تأییدشده با grep رویِ کلِ api/src):
--  اپِ مشتری پنج کلیدِ ترجیحِ اعلان دارد («میز خالی شد»، «تخفیف و کش‌بک ویژه»،
--  «یادآوری رزرو»، «امتیاز و پاداش»، «DNA غذایی»). `setNotifPref` آن‌ها را
--  **فقط در localStorage** می‌نوشت و هیچ‌وقت به سرور نمی‌فرستاد. سمتِ سرور هم
--  هیچ مفهومی از رضایتِ کاربر وجود نداشت — نه ستونی، نه فیلدی، نه چکی.
--
--  نتیجه: کاربری که «تخفیف و کش‌بک ویژه» را خاموش می‌کرد همچنان پیامکِ
--  کمپینِ تبلیغاتی می‌گرفت (`POST /restaurant/sms` همه‌ی اعضایِ باشگاه را
--  بدونِ هیچ فیلتری صدا می‌زند). انتخابِ کاربر بی‌صدا دور ریخته می‌شد و با
--  پاک‌کردنِ حافظه‌ی مرورگر کاملاً از بین می‌رفت.
--
--  طراحی — عمداً کمینه (§۳۵: نقطه‌ی گسترشِ ارزان، نه over-build):
--   • یک ستونِ jsonb به‌جایِ پنج ستونِ boolean: مجموعه‌ی دسته‌ها یک تصمیمِ
--     محصولی است و تغییر می‌کند؛ ستونِ جدید برایِ هر دسته یعنی migration جدید.
--   • پیش‌فرضِ `{}` یعنی «کاربر چیزی نگفته» → رفتارِ فعلی (opt-in) حفظ می‌شود
--     و هیچ کاربرِ موجودی بی‌صدا از دریافت خارج نمی‌شود.
--   • فقط «خاموشِ صریح» احترام گذاشته می‌شود؛ نبودِ کلید = رضایتِ ضمنیِ قبلی.
--   • ایندکس عمداً ساخته **نمی‌شود**: تنها مصرف‌کننده، خواندنِ نقطه‌ایِ همان
--     کاربر (PK) و فیلترِ درون‌حافظه‌ایِ فهرستِ کمپین است.
--
--  ⚠️ این ستون باید در schema.prisma هم اعلام شود (گاردِ
--  tests/schema-drift.integration.test.mts) — انجام شد.
-- ═══════════════════════════════════════════════════════════════════════

ALTER TABLE users
  ADD COLUMN IF NOT EXISTS notification_prefs jsonb NOT NULL DEFAULT '{}'::jsonb;

COMMENT ON COLUMN users.notification_prefs IS
  'ترجیحاتِ اعلان به‌ازای دسته. کلیدِ غایب = کاربر نظری نداده (پیش‌فرضِ دریافت). فقط false صریح یعنی انصراف.';
