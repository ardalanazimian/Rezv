-- ۰۷۴ — ورود با نامِ کاربری و رمزِ عبور برای کارکنان و مدیرِ پلتفرم
--
-- ⚠️ چرا: تنها راهِ ورود به هر سه اپ OTPِ پیامکی بود و `OTP_DEV_MODE` در
-- production استثنا پرتاب می‌کند. یعنی بدونِ `KAVENEGAR_API_KEY` **هیچ‌کس**
-- نمی‌توانست وارد پنل شود — نه صاحبِ رستوران، نه مدیرِ پلتفرم. این ستون‌ها
-- یک مسیرِ ورودِ دومِ مستقل از پیامک می‌سازند.
--
-- ⚠️ OTP **حذف نمی‌شود**: مسیرِ ورودِ مشتری (اپِ customer) همچنان با شماره و
-- کد است و باید بماند. این فقط برای پنل‌هاست.
--
-- ── چرا `username` یکتای **سراسری** و نه per-tenant ──
-- فرمِ ورود فقط نام‌کاربری و رمز می‌گیرد؛ اگر یکتایی per-tenant بود، سرور
-- نمی‌دانست کدام تنانت را نگاه کند و مجبور بودیم یا انتخابگرِ تنانت به فرم
-- اضافه کنیم یا «اولین تطبیق» را برداریم — که دقیقاً همان کلاسِ باگی است که
-- مهاجرتِ ۰۷۲ برای شماره‌ی تلفن بست (هایجکِ تنانت). یکتاییِ سراسری این
-- ابهام را از ریشه حذف می‌کند.
--
-- ── حساسیت به حروفِ بزرگ/کوچک ──
-- کاربر `Ardalan` را تایپ می‌کند و انتظار دارد همان حسابِ `ardalan` باشد.
-- این با `normalizeUsername()` در `api/src/lib/password.ts` تضمین می‌شود که
-- **هم** در هر مسیرِ نوشتن و **هم** در هر مسیرِ خواندن صدا زده می‌شود؛ یعنی
-- مقدارِ داخلِ ستون همیشه از قبل lowercase است و ایندکسِ سادهٔ یکتا دقیقاً
-- همان کار را می‌کند.
--
-- ⚠️ نسخه‌ی اولِ این مهاجرت ایندکسِ **تابعی** روی `lower(username)` می‌ساخت
-- (به‌عنوانِ لایه‌ی دوم، اگر روزی یک مسیر نرمال‌سازی را فراموش کند). عوض شد
-- چون Prisma ایندکسِ تابعی را بیان نمی‌کند: `db push` (مسیرِ CI) نسخه‌ی
-- ساده می‌ساخت و `apply-sql` (مسیرِ تولید) نسخه‌ی تابعی — یعنی همان
-- «CI سبز، تولید متفاوت» که دروازه‌ی انحرافِ اسکیما برایش ساخته شده. نامِ
-- ایندکس هم عمداً همانی است که Prisma برای `@@unique([username])` تولید
-- می‌کند، وگرنه `db push` یک ایندکسِ دومِ هم‌معنا با نامِ دیگر می‌ساخت.
-- گاردِ نرمال‌سازی به‌جایش با تست قفل شده (نه با ایندکس).
-- `NULL`ها در قیدِ یکتای Postgres با هم برخورد نمی‌کنند، پس کارکنانی که
-- نام‌کاربری ندارند (ورودِ فقط-OTP) بی‌اثر می‌مانند.
--
-- ── چرا `password_hash` متن است و نه bytea ──
-- قالبِ ذخیره خودتوصیف است (`scrypt$N$r$p$salt$hash`)، تا سخت‌ترکردنِ
-- پارامترها در آینده نیازی به مهاجرتِ دیتابیس نداشته باشد. جزئیات در
-- `api/src/lib/password.ts`.
-- ═══════════════════════════════════════════════════════════════════════

